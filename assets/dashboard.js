  function refresh() {
    var ws = slice();
    state.charts.forEach(function (entry) {
      var c = entry.chart;
      if (entry.deltas) c.cfg.deltas = entry.deltas(ws);
      if (entry.platform) c.cfg.scale = state.scale;
      c.setData(cats(ws), entry.data(ws), entry.metric ? flagsFor(ws, entry.metric) : []);
    });
    buildTable();
  }

